def stack(top: int, inner: str, gap: int = 12) -> str:
    return (
        f'<div style="position: absolute; left: {MARGIN}px; right: {MARGIN}px; top: {top}px; display: flex; flex-direction: column; '
        f'gap: {gap}px">{inner}</div>'
    )


def rows(p: Phone, items: list[tuple[str, str, str]], height: int = 48) -> str:
    """A grouped list of (label, value, tail) where tail is "chevron", "external" or "".
    """
    c = p.c
    out = []
    for i, (label, value, tail) in enumerate(items):
        border = "" if i == len(items) - 1 else f"border-bottom: 1px solid {c['divider']}; "
        mark = icon(tail, c["textSecondary"], 14 if tail == "chevron" else 18) if tail else ""
        val = f'<span style="color: {c["textSecondary"]}">{value}</span>' if value else ""
        out.append(
            f'<div style="display: flex; align-items: center; gap: 10px; height: {height}px; padding: 0 14px; {border}font-size: 16px">'
            f'<span style="flex-grow: 1">{label}</span>{val}{mark}</div>'
        )
    return f'<div style="background: {c["surface"]}; border-radius: 14px; overflow: hidden">{"".join(out)}</div>'


def banner(p: Phone, tone: str, title: str, lines: list[str], close: bool = True) -> str:
    """An inline message in the Banner component's information or warning tone."""
    c = p.c
    colours = {"information": ("primaryTint", "primary", "primaryText", "info"),
               "warning": ("bannerWarning", "bannerWarningBorder", "textPrimary", "warning")}
    fill, border, ink, glyph = colours[tone]
    fill_c, border_c, ink_c = c[fill], c[border], c[ink]
    body = "".join(f'<div style="font-size: 14px; line-height: 1.4">{line}</div>' for line in lines)
    x = (
        f'<button aria-label="Close" style="width: 44px; height: 44px; margin: -10px -10px 0 0; border: 0; padding: 0; background: transparent; '
        f'display: flex; align-items: center; justify-content: center">{icon("close", c["textSecondary"], 18)}</button>'
        if close
        else ""
    )
    return (
        f'<div role="status" style="display: flex; gap: 10px; padding: 12px 12px 12px 14px; border-radius: 14px; background: {fill_c}; '
        f'border: 1.5px solid {border_c}; box-sizing: border-box">'
        f'<div style="padding-top: 1px">{icon(glyph, ink_c, 20)}</div>'
        f'<div style="flex-grow: 1; display: flex; flex-direction: column; gap: 3px">'
        f'<div style="font-size: 15px; font-weight: 600">{title}</div>{body}</div>{x}</div>'
    )


