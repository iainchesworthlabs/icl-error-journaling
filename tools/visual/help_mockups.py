def tab_bar(p: Phone, selected: int) -> str:
    c = p.c
    names = [("log", "Log"), ("review", "Review"), ("history", "History"), ("settings", "Settings")]
    items = []
    for i, (glyph, label) in enumerate(names):
        colour = c["primaryText"] if i == selected else c["textSecondary"]
        weight = 600 if i == selected else 500
        items.append(
            f'<div style="display: flex; flex-direction: column; align-items: center; gap: 3px; color: {colour}; '
            f'font-size: 10.5px; font-weight: {weight}">{icon(glyph, colour)}{label}</div>'
        )
    return (
        f'<nav style="position: absolute; left: 0; right: 0; bottom: 0; height: {TAB_BAR}px; box-sizing: border-box; padding-top: 8px; '
        f'background: {c["surface"]}; border-top: 1px solid {c["tabBarBorder"]}; display: grid; '
        f'grid-template-columns: repeat(4, minmax(0, 1fr))">{"".join(items)}</nav>'
    )


def help_button(p: Phone, name: str) -> str:
    """The shared help button: a question mark in a 44 pt target, with the accessible name of its topic."""
    c = p.c
    return (
        f'<button aria-label="{name}" style="width: 44px; height: 44px; border: 0; padding: 0; background: transparent; '
        f'display: flex; align-items: center; justify-content: center">{icon("help", c["primaryText"], 24)}</button>'
    )


