"""Write the in-app help mock-ups of Stage 10 (docs/design/screens/<Name>.dc.html and <Name>.dark.dc.html).

    python tools/visual/help_mockups.py [--check]

Stage 10, package 10.5 (docs/plan/stage-10.md, "In-app help"). The seven screens are drawn for the owner's review before
10.6 writes any QML:

    HelpSheet           a help sheet (the board layout topic) with "Read more in the guide"
    HelpSheetLarge      the same at a very large text size (illustrative: 2.2 times; the app's largest is larger still)
    SettingsHelp        the Settings list scrolled to the end, with the Help group
    SettingsQuickHelp   the Quick help list that the Help group opens
    LogFirstRunTip      the Log screen with the first-run tip card (after Close it is the Log screen as it is today)
    ErrorTypesHelp      the Error types list with its explanatory line and its help button
    ImportErrorsHelp    Import refused, with the "How to fix a setup file" row and a help button

They are plain static HTML at the phone's frame (402 x 874 pt, as the other phone mock-ups) and reuse the building blocks and
the colours of tools/visual/ipad_mockups.py (every colour comes from docs/design/tokens.json). The wording is the proposed
wording of the in-app help and the same as `HelpTopics` will hold. Change it here, then run the script again. With --check
it writes nothing and fails when a file is not what it would write.
"""

