class Phone(Page):
    """A phone mock-up page: the colours of Page, the frame of the phone, and a document of its own."""

    def __init__(self, dark: bool, scale: float = 1.0) -> None:
        super().__init__(PHONE, dark)
        self.scale = scale

    def fs(self, px: float) -> str:
        """A font size in px at this page's text scale."""
        value = round(px * self.scale, 1)
        return f"{value:g}px"

    def document(self, title: str, body: str, background: str | None = None) -> str:  # type: ignore[override]
        c = self.c
        bg = background or c["background"]
        props = json.dumps({"$preview": {"width": PHONE.width, "height": PHONE.height}}, separators=(",", ":"))
        return (
            "<!doctype html>\n"
            '<html lang="en">\n<head>\n<meta charset="utf-8">\n'
            f"<title>{title}{' (dark)' if self.dark else ''}</title>\n"
            '<script src="./support.js"></script>\n</head>\n<body>\n<x-dc>\n<helmet>\n'
            '<link rel="preconnect" href="https://fonts.googleapis.com">\n'
            '<link href="https://fonts.googleapis.com/css2?family=Inter:wght@400;500;600;700&amp;display=swap" rel="stylesheet">\n'
            "<style>\nbody{margin:0}\n</style>\n</helmet>\n"
            "<!-- Generated by tools/visual/help_mockups.py from docs/design/tokens.json. Edit the script, not this file. -->\n"
            f'<div style="width: {PHONE.width}px; height: {PHONE.height}px; position: relative; overflow: hidden; background: {bg}; '
            f'font-family: Inter, -apple-system, system-ui, sans-serif; color: {c["textPrimary"]}">\n'
            f"{body}\n</div>\n</x-dc>\n"
            f"<script type=\"text/x-dc\" data-dc-script data-props='{props}'>\n"
            "class Component extends DCLogic {}\n</script>\n</body>\n</html>\n"
        )


